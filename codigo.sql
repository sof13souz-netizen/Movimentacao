CREATE TABLE USUARIO (
ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- GENERATED BY DEFAULT AS IDENTITY = o banco gera automaticamente um número para cada novo usuário. É o "autoincremento" do Firebird nesse formato. PRIMARY KEY = identifica cada usuário de forma única.
NOME VARCHAR(100),
EMAIL VARCHAR(100) UNIQUE, --UNIQUE não permite dois usuários com o mesmo e-mail.
SENHA VARCHAR(254),
TIPO INTEGER,
ATIVO BOOLEAN NOT NULL, --boolean é o valor lógico com TRUE = ativo e FALSE = inativo , NOT NULL significa que o campo não pode ficar vazio
TENTATIVAS_LOGIN INTEGER NOT NULL, --NOT NULL - não pode estar vazio
BLOQUEADO BOOLEAN NOT NULL -- FALSE = usuario nao bloqueado, TRUE usuário bloqueado
)

CREATE TABLE HISTORICO_SENHA (
ID_HISTORICO_SENHA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
SENHA VARCHAR(254),
ID_USUARIO INTEGER,
CONSTRAINT FK_USUARIO FOREIGN KEY (ID_USUARIO) -- CONSTRAINT é um restrição/regra que vai ser criada no banco, então fk_usuario é o nome da chave estrangeira
-- foreign key faz ligação entre as tabelas (chave estrangeira)
REFERENCES USUARIO (ID_USUARIO) -- indica qual tabela e coluna essa chave estrangeira aponta
)

